export type LocaleCode = (typeof LOCALE_CATALOG)[number]['code'];

export type LocaleCatalogEntry = (typeof LOCALE_CATALOG)[number];

export const LOCALE_CODES = LOCALE_CATALOG.map(
	(entry) => entry.code
) as readonly LocaleCode[];

const catalogByCode = new Map<string, LocaleCatalogEntry>(
	LOCALE_CATALOG.map((entry) => [entry.code, entry])
);

export function getLocaleCatalogEntry(
	code: string
): LocaleCatalogEntry | undefined {
	return catalogByCode.get(code);
}

/** Catalog entry, or a safe fallback when Paraglide has a code the catalog lacks. */
export type LocaleDisplayEntry = {
	code: string;
	englishName: string;
	nativeName: string;
	flag: string;
};

export function resolveLocaleCatalogEntry(
	code: string
): LocaleDisplayEntry {
	const known = catalogByCode.get(code);
	if (known) return known;
	return {
		code,
		englishName: code,
		nativeName: code,
		flag: '🏳️'
	};
}

export function formatLocaleLabel(entry: LocaleDisplayEntry): string {
	if (entry.nativeName === entry.englishName) {
		return `${entry.flag} ${entry.nativeName}`;
	}
	return `${entry.flag} ${entry.nativeName} (${entry.englishName})`;
}

/** Accessible name without relying on emoji alone. */
export function formatLocaleAriaLabel(
	entry: LocaleDisplayEntry
): string {
	if (entry.nativeName === entry.englishName) {
		return entry.englishName;
	}
	return `${entry.nativeName} (${entry.englishName})`;
}

/** WashSelect / list options: Paraglide `locales` joined with catalog metadata. */
export function localeSelectOptions(
	localeCodes: readonly string[]
): { value: string; label: string }[] {
	return localeCodes.map((code) => {
		const entry = resolveLocaleCatalogEntry(code);
		return {
			value: code,
			label: formatLocaleLabel(entry)
		};
	});
}

export function isLocaleCode(value: string): value is LocaleCode {
	return catalogByCode.has(value);
}

/** Sorted catalog for searchable pickers (English name, then code). */
export function filterLocaleSelectOptions(
	options: readonly { value: string; label: string }[],
	query: string
): { value: string; label: string }[] {
	const q = query.trim().toLowerCase();
	if (!q) return [...options];
	return options.filter((opt) => {
		const entry = resolveLocaleCatalogEntry(opt.value);
		return (
			opt.value.toLowerCase().includes(q) ||
			opt.label.toLowerCase().includes(q) ||
			entry.englishName.toLowerCase().includes(q) ||
			entry.nativeName.toLowerCase().includes(q)
		);
	});
}
