/**
 * Paraglide compile wrapper.
 *
 * Default outputStructure=locale-modules (~one file per locale) keeps dev and
 * Vite stable. Use --message-modules before production builds for better
 * tree-shaking (then run with --clean once when switching structure).
 *
 * Default cleanOutdir=false avoids wiping src/lib/paraglide while Vite dev is
 * running (mass HMR + missing runtime.js SSR errors). Use --clean for a full rebuild.
 */
import { compile } from '@inlang/paraglide-js';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(
	fileURLToPath(new URL('.', import.meta.url)),
	'..'
);
const outdir = resolve(root, 'src/lib/paraglide');
const cleanOutdir = process.argv.includes('--clean');
const messageModules = process.argv.includes('--message-modules');

/**
 * Drop generated JSDoc from the compiled output.
 *
 * Paraglide writes the full 195-locale union (`locale?: "en" | "hi" | ...`) once
 * per message. `_index.js` alone is 49 MB of that; stripping it to 36 MB keeps
 * 2814 identical exports and cuts Vite's first-request transform peak from ~9 GB
 * to about half (measured), which is what OOMed the dev server.
 * `tsconfig.json` excludes `src/lib/paraglide`, so nothing type-checks these.
 */
function stripGeneratedJsDoc(dir) {
	let bytesBefore = 0;
	let bytesAfter = 0;
	for (const entry of readdirSync(dir, { withFileTypes: true })) {
		const full = resolve(dir, entry.name);
		if (entry.isDirectory()) {
			const nested = stripGeneratedJsDoc(full);
			bytesBefore += nested.bytesBefore;
			bytesAfter += nested.bytesAfter;
			continue;
		}
		if (!entry.name.endsWith('.js')) continue;
		const source = readFileSync(full, 'utf8');
		// Messages are JSON strings, so `/**` or `*\/` in copy is impossible.
		const stripped = source.replace(
			/\/\*\*[^*]*(?:\*(?!\/)[^*]*)*\*\/\s*/g,
			''
		);
		bytesBefore += source.length;
		bytesAfter += stripped.length;
		if (stripped.length !== source.length)
			writeFileSync(full, stripped);
	}
	return { bytesBefore, bytesAfter };
}

await compile({
	project: resolve(root, 'project.inlang'),
	outdir,
	cleanOutdir,
	outputStructure: messageModules
		? 'message-modules'
		: 'locale-modules',
	// Messages are emitted as .js only. Without a declaration, TS errors on every
	// `import { m } from '$lib/paraglide/messages'` (301 files). `emitTsDeclarations`
	// is not used: it takes >10 min. Every call site already treats `m` as a
	// key→function record, so one declaration covers them all.
	additionalFiles: {
		'messages.d.ts': [
			'// Generated by scripts/compile-paraglide.mjs',
			'export declare const m: Record<',
			'  string,',
			'  (inputs?: Record<string, unknown>) => string',
			'>;'
		].join('\n'),
		'runtime.d.ts': [
			'// Generated by scripts/compile-paraglide.mjs',
			'export declare const baseLocale: string;',
			'export declare const locales: readonly string[];',
			'export declare const cookieName: string;',
			'export declare const cookieMaxAge: number;',
			'export declare const cookieDomain: string;',
			'export declare const localStorageKey: string;',
			'export declare const strategy: readonly string[];',
			'export declare const urlPatterns: readonly unknown[];',
			'export declare const isServer: boolean;',
			'export declare const disableAsyncLocalStorage: boolean;',
			'export declare const experimentalMiddlewareLocaleSplitting: boolean;',
			'export declare const experimentalStaticLocale: string | undefined;',
			'export declare function getLocale(): string;',
			'export declare function setLocale(newLocale: string, options?: unknown): void;',
			'export declare function deLocalizeUrl(url: string | URL): URL;',
			'export declare function localizeUrl(url: string | URL): URL;',
			'export declare function localizeHref(href: string): string;',
			'export declare function deLocalizeHref(href: string): string;'
		].join('\n'),
		'server.d.ts': [
			'// Generated by scripts/compile-paraglide.mjs',
			'export declare function paraglideMiddleware<Result>(',
			'  request: Request,',
			'  resolve: (args: { request: Request; locale: string }) => Result,',
			'  callbacks?: { onRedirect?: (url: URL) => void; disableAsyncLocalStorage?: boolean }',
			'): Promise<Result>;'
		].join('\n')
	}
});

const { bytesBefore, bytesAfter } = stripGeneratedJsDoc(outdir);

console.log(
	`Paraglide compile finished (cleanOutdir=${cleanOutdir}, outputStructure=${messageModules ? 'message-modules' : 'locale-modules'}). ` +
		`JSDoc stripped: ${(bytesBefore / 1048576).toFixed(0)}MB -> ${(bytesAfter / 1048576).toFixed(0)}MB.`
);
