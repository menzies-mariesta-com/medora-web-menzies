// Generates per-route API GET cache tiers for all api +server.ts routes.
// Run: node scripts/generate-api-cache-policy.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(
	path.dirname(fileURLToPath(import.meta.url)),
	'..'
);
// Client-safe location: the browser needs the template map to validate hover prefetch targets.
const outFile = path.join(
	root,
	'src/lib/util/api-route-tier.generated.ts'
);

function walkApiServers(dir) {
	const out = [];
	for (const name of fs.readdirSync(dir)) {
		const p = path.join(dir, name);
		const st = fs.statSync(p);
		if (st.isDirectory()) out.push(...walkApiServers(p));
		else if (name === '+server.ts') out.push(p);
	}
	return out;
}

function fileToTemplate(filePath) {
	const rel = path
		.relative(path.join(root, 'src/routes'), filePath)
		.replace(/\\/g, '/')
		.replace(/\/\+server\.ts$/, '');
	return (
		'/' +
		rel
			.replace(/\([^)]+\)\//g, '')
			.replace(/\[\.\.\.([^\]]+)\]/g, '*')
			.replace(/\[([^\]]+)\]/g, ':$1')
	);
}

function hasGetHandler(source) {
	return /export\s+(const\s+GET|async\s+function\s+GET)/.test(source);
}

/** Assign tier id per route template (GET routes only; mutation-only → no-store). */
function classify(template, getEnabled) {
	if (!getEnabled) return 'no-store';

	const t = template;

	const noStorePrefix = [
		'/api/ai/',
		'/api/auth',
		'/api/cron/',
		'/api/doctor/',
		'/api/patient/',
		'/api/session/',
		'/api/upload/',
		'/api/support-ticket',
		'/api/patient-attachment/',
		'/api/patient-photo/',
		'/api/staff-photo/',
		'/api/staff-signature/',
		'/api/hospital-logo/',
		'/api/grn-invoice/',
		'/api/public/pricing/',
		'/api/pricing/',
		'/api/medora/auth/',
		'/api/medora/notification',
		'/api/medora/staff/self'
	];
	if (
		noStorePrefix.some(
			(p) => t.startsWith(p) || t === p.replace(/\/$/, '')
		)
	) {
		return 'no-store';
	}

	if (t.startsWith('/api/medora/master/')) return 'master-long';

	if (/\/home\/billing\//.test(t)) return 'no-store';
	if (
		/\/home\/(adt|consultation|clinical-form|medication-order|obstetrics)\//.test(
			t
		)
	) {
		return 'no-store';
	}
	if (/\/home\/nursing-workbench\//.test(t)) return 'no-store';
	if (/\/home\/emergency/.test(t) && !/\/administration\//.test(t)) {
		return 'no-store';
	}
	if (/\/home\/registration\/patient\//.test(t)) return 'no-store';
	if (/\/home\/emr\//.test(t)) return 'no-store';
	if (/\/home\/inventory\/reports\//.test(t)) return 'report-medium';
	if (/\/home\/inventory\/(?!setup)/.test(t)) return 'no-store';
	if (/\/home\/perioperative\/(events|surgical-case)/.test(t)) {
		return 'no-store';
	}
	if (
		/\/home\/diagnostics\/lab\/(worklist|collection-worklist|critical-callback|receive|results|integration)/.test(
			t
		)
	) {
		return 'no-store';
	}
	if (/\/home\/document-print/.test(t)) return 'no-store';

	if (/\/home\/administration\//.test(t)) return 'master-long';
	if (/\/home\/inventory-setup\//.test(t)) return 'master-long';
	if (/\/home\/diagnostics\/lab\/catalog/.test(t))
		return 'master-long';
	if (/\/home\/perioperative\/ot-room/.test(t)) return 'master-long';
	if (/\/home\/account-settings/.test(t)) return 'account-medium';

	if (/\/home\/dashboard/.test(t)) return 'dashboard-short';
	if (/\/home\/diagnostics\/lab\/dashboard/.test(t))
		return 'dashboard-short';

	if (t.startsWith('/api/medora/admin/plans')) return 'no-store';
	if (t.startsWith('/api/medora/admin/')) return 'admin-medium';
	if (t === '/api/medora/hospital') return 'admin-medium';

	return 'default-short';
}

const servers = walkApiServers(path.join(root, 'src/routes/api'));
const tiers = {};
for (const file of servers.sort()) {
	const template = fileToTemplate(file);
	const source = fs.readFileSync(file, 'utf8');
	const getEnabled = hasGetHandler(source);
	tiers[template] = classify(template, getEnabled);
}

const header = `/* AUTO-GENERATED by scripts/generate-api-cache-policy.mjs — do not edit */
export type ApiRouteTierId =
\t| 'no-store'
\t| 'master-long'
\t| 'picker-long'
\t| 'account-medium'
\t| 'admin-medium'
\t| 'report-medium'
\t| 'dashboard-short'
\t| 'default-short';

/** Per-route GET cache tier (${servers.length} API handlers). */
export const API_ROUTE_TIER_BY_TEMPLATE: Record<string, ApiRouteTierId> = `;

const body = `${header}${JSON.stringify(tiers, null, '\t')} as const satisfies Record<string, ApiRouteTierId>;\n`;

fs.writeFileSync(outFile, body);
console.log(
	`Wrote ${servers.length} routes → ${path.relative(root, outFile)}`
);
